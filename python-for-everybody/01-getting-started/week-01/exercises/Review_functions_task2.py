#Task 2: One parameter
#Write square(n) that returns n times n.
#  Call it with 4, store the result in a variable, and print it. 
# What happens if you call square(4) on its own line, without storing or printing it?


#task2
def square(n):
    return n * n

result= square(4)
print(result)
#or print(square(4))

#The function’s answer only appears if you print what the call returns.
#Rule: a call that returns a value is like a question with an answer. If you don’t store or print the answer, it’s lost.

